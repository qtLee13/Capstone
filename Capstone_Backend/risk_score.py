# AI ต่ำกว่าค่านี้ + ไม่มีไฟล์แนบอันตราย = ข้าม Stage 2 (VirusTotal/IPQS/DMARC)
# ⚠️ main.py บังคับเพิ่มอีกชั้น: ถ้าใน body มี URL ห้ามเข้า fast path เด็ดขาด
SAFE_AI_THRESHOLD = 30


def is_fast_path_safe(raw_ai_score: float, has_malware: bool) -> bool:
    """True = ข้าม external check ได้ (raw_signals ยังส่งกลับ Gateway ครบเหมือนเดิม)"""
    return raw_ai_score < SAFE_AI_THRESHOLD and not has_malware
